"use client";

import { useLiveQuery } from "dexie-react-hooks";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { useState } from "react";
import { type Cents, formatPeso } from "@/core/money";
import { formatStoreDay, STORE_TIME_ZONE, storeDay } from "@/core/time";
import {
  buildStatement,
  type Statement,
  type StatementPeriod,
} from "@/modules/ledger/application/statement";
import { formatPhilippineMobile } from "@/modules/ledger/domain/customer";
import { type CustomerId } from "@/modules/ledger/domain/ids";
import { useApp } from "@/app/providers";
import { EmptyState } from "@/ui/empty-state";
import { Icon } from "@/ui/icons";
import { useMinimumDelay } from "@/ui/use-minimum-delay";

type PeriodKey = "since-paid" | "this-month" | "last-month" | "all";

const peso = (c: number, sign: "auto" | "always" = "auto") => formatPeso(c as Cents, { sign });
const noon = (day: string) => new Date(`${day}T04:00:00Z`);
const stampFmt = new Intl.DateTimeFormat("en-PH", {
  dateStyle: "medium",
  timeStyle: "short",
  timeZone: STORE_TIME_ZONE,
});

function monthOf(now: Date, offset: number): string {
  const [y, m] = storeDay(now).split("-").map(Number) as [number, number];
  const d = new Date(Date.UTC(y, m - 1 + offset, 1));
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}`;
}

function periodFor(key: PeriodKey, settledAt: Date | null, now: Date): StatementPeriod {
  if (key === "since-paid") return { kind: "since-paid", after: settledAt };
  if (key === "this-month") return { kind: "month", month: monthOf(now, 0) };
  if (key === "last-month") return { kind: "month", month: monthOf(now, -1) };
  return { kind: "all" };
}

function periodText(s: Statement, now: Date): string {
  const to = formatStoreDay(noon(s.to), now);
  return s.from ? `${formatStoreDay(noon(s.from), now)} – ${to}` : `Up to ${to}`;
}

/** Plain-text version for messaging apps (Copy / Share). */
function statementText(s: Statement, store: string, now: Date): string {
  const lines = [
    `${store}`,
    `Statement of account ${s.number}`,
    `Client: ${s.customer.name}`,
    `Period: ${periodText(s, now)}`,
    "",
    `Opening balance: ${peso(s.opening)}`,
    ...s.rows.map(
      (r) =>
        `${formatStoreDay(r.entry.occurredAt, now)}  ${r.entry.note ?? (r.entry.kind === "bayad" ? "Bayad" : "Utang")}  ${peso(r.entry.amount, "always")}  → ${peso(r.balance)}`,
    ),
    "",
    `Total utang: ${peso(s.totalUtang)}`,
    `Total bayad: ${peso(s.totalBayad)}`,
    `Balance due: ${peso(s.balanceDue)}`,
    "",
    `Generated by Atrazo · ${stampFmt.format(s.generatedAt)}`,
  ];
  return lines.join("\n");
}

/** /statement?id=… : a client's statement of account, to print, save as PDF, copy or share. */
export function StatementScreen() {
  const { phone, toast } = useApp();
  const id = useSearchParams().get("id") as CustomerId | null;
  const data = useLiveQuery(async () => {
    if (!phone || !id) return undefined;
    const [customer, entries, ledger, settings] = await Promise.all([
      phone.db.customers.get(id),
      phone.db.entries.where("customerId").equals(id).toArray(),
      phone.queries.customerLedger(id),
      phone.queries.settings(),
    ]);
    return customer && ledger
      ? { customer, entries, settledAt: ledger.account.settledAt, store: settings.name }
      : null;
  }, [phone, id]);
  const shown = useMinimumDelay(id);
  const [choice, setChoice] = useState<PeriodKey | null>(null);

  const back = (
    <Link
      href={id ? `/client?id=${id}` : "/"}
      className="icon-btn"
      aria-label="Back to the client"
      style={{ color: "#fff" }}
    >
      <Icon name="back" size={22} />
    </Link>
  );

  if (data === undefined || !shown) {
    return (
      <div className="app solo stmt-screen">
        <header className="bar" style={{ paddingLeft: 4 }}>
          {back}
          <div className="bar-title">
            <h1>Statement</h1>
          </div>
        </header>
        <main className="vscroll stmt-main" aria-busy="true" aria-label="Loading the statement">
          <div className="skeleton" style={{ height: 40 }} />
          <div
            className="card"
            style={{ padding: 18, display: "flex", flexDirection: "column", gap: 14 }}
          >
            {[50, 70, 40, 90, 90, 90, 60].map((w, i) => (
              <span
                key={i}
                className="skeleton"
                style={{ display: "block", height: 14, width: `${w}%` }}
              />
            ))}
          </div>
        </main>
      </div>
    );
  }

  if (data === null) {
    return (
      <div className="app solo stmt-screen">
        <header className="bar" style={{ paddingLeft: 4 }}>
          {back}
          <div className="bar-title">
            <h1>Statement</h1>
          </div>
        </header>
        <main className="vscroll stmt-main">
          <EmptyState
            art={<Icon name="file" size={26} />}
            compact
            title="Client not found"
            body="This client may have been removed from this phone."
            action={
              <Link href="/" className="btn btn-secondary">
                Back to clients
              </Link>
            }
          />
        </main>
      </div>
    );
  }

  const now = new Date();
  const key: PeriodKey = choice ?? (data.settledAt ? "since-paid" : "all");
  const s = buildStatement(data.customer, data.entries, periodFor(key, data.settledAt, now), now);
  const periods: { key: PeriodKey; label: string }[] = [
    ...(data.settledAt ? [{ key: "since-paid" as const, label: "Since paid" }] : []),
    { key: "this-month", label: "This month" },
    { key: "last-month", label: "Last month" },
    { key: "all", label: "All" },
  ];

  async function copy() {
    await navigator.clipboard?.writeText(statementText(s, data!.store, now));
    toast({ title: "Statement copied", detail: "Paste it into Messenger, Viber or SMS" });
  }
  async function share() {
    const text = statementText(s, data!.store, now);
    if (navigator.share) {
      await navigator
        .share({ title: `Statement for ${s.customer.name}`, text })
        .catch(() => undefined);
    } else {
      await copy();
    }
  }

  return (
    <div className="app solo stmt-screen">
      <header className="bar" style={{ paddingLeft: 4 }}>
        {back}
        <div className="bar-title">
          <h1>Statement</h1>
          <span className="bar-sub">{s.customer.name}</span>
        </div>
      </header>

      <main className="vscroll stmt-main">
        <div className="seg stmt-periods" role="group" aria-label="Statement period">
          {periods.map((p) => (
            <button
              key={p.key}
              type="button"
              aria-pressed={key === p.key}
              onClick={() => setChoice(p.key)}
            >
              {p.label}
            </button>
          ))}
        </div>

        <article className="stmt-doc" aria-label={`Statement of account for ${s.customer.name}`}>
          <header className="stmt-head">
            <div>
              <strong className="disp stmt-store">{data.store}</strong>
              <span className="stmt-kind">Statement of account</span>
            </div>
            <span className="stmt-no mono">#{s.number}</span>
          </header>

          <dl className="stmt-meta">
            <div>
              <dt>Client</dt>
              <dd>{s.customer.name}</dd>
            </div>
            {s.customer.phone && (
              <div>
                <dt>Phone</dt>
                <dd className="mono">{formatPhilippineMobile(s.customer.phone)}</dd>
              </div>
            )}
            <div>
              <dt>Period</dt>
              <dd>{periodText(s, now)}</dd>
            </div>
            <div>
              <dt>Opening balance</dt>
              <dd className="mono">{peso(s.opening)}</dd>
            </div>
          </dl>

          {s.rows.length === 0 ? (
            <p className="stmt-none">No utang or bayad in this period.</p>
          ) : (
            <table className="tbl stmt-tbl">
              <thead>
                <tr>
                  <th scope="col" style={{ width: 62 }}>
                    Date
                  </th>
                  <th scope="col">Details</th>
                  <th scope="col" className="num" style={{ width: 92 }}>
                    Amount
                  </th>
                  <th scope="col" className="num" style={{ width: 92 }}>
                    Balance
                  </th>
                </tr>
              </thead>
              <tbody>
                {s.rows.map((r) => (
                  <tr key={r.entry.id}>
                    <td>{formatStoreDay(r.entry.occurredAt, now)}</td>
                    <td>{r.entry.note ?? (r.entry.kind === "bayad" ? "Bayad" : "Utang")}</td>
                    <td className={`num mono ${r.entry.kind === "bayad" ? "stmt-bayad" : ""}`}>
                      {peso(r.entry.amount, "always")}
                    </td>
                    <td className="num mono">{peso(r.balance)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}

          <dl className="stmt-totals">
            <div>
              <dt>Total utang</dt>
              <dd className="mono">{peso(s.totalUtang)}</dd>
            </div>
            <div>
              <dt>Total bayad</dt>
              <dd className="mono stmt-bayad">{peso(s.totalBayad)}</dd>
            </div>
            <div className="stmt-due">
              <dt>Balance due</dt>
              <dd className="mono disp">{peso(s.balanceDue)}</dd>
            </div>
          </dl>

          <footer className="stmt-foot">
            <span>Generated by Atrazo · {stampFmt.format(s.generatedAt)}</span>
            <span>Page 1 of 1</span>
          </footer>
        </article>

        <p className="stmt-note">
          Voided entries are left out. The balance due matches {s.customer.name}’s ledger at the end
          of the period.
        </p>
      </main>

      <footer className="action-bar stmt-actions">
        <button type="button" className="btn btn-secondary" onClick={() => void copy()}>
          <Icon name="copy" size={16} />
          Copy as text
        </button>
        <button type="button" className="btn btn-secondary" onClick={() => void share()}>
          <Icon name="message" size={16} />
          Share
        </button>
        <button type="button" className="btn btn-dark" onClick={() => window.print()}>
          <Icon name="file" size={16} />
          Print / PDF
        </button>
      </footer>
    </div>
  );
}
